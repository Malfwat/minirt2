#include <semaphore.h>

void	sem_n_post(sem_t *s, int n)
{
	int	i;

	i = 0;
	while (i++ < n)
		sem_post(s);
}

void	sem_n_wait(sem_t *s, int n)
{
	int	i;

	i = 0;
	while (i++ < n)
		sem_wait(s);
}
